/// Where Auto has landed, as a name.
/// Which noise profile the chain is running under, however it was arrived at.
///
/// **Shown for all five settings, not only `Auto`.** It used to appear only
/// under `Auto`, on the reasoning that the other four would just repeat a
/// choice the rider had already made. That reasoning does not survive contact:
/// the panel is read when something sounds wrong, often on a device somebody
/// else configured or that was set months ago, and "which profile is this even
/// running?" is then the first question. Repeating an answer costs one line;
/// withholding it sent three separate reports that the profile line was
/// missing, when in every case the profile was simply set by hand.
///
/// The wording distinguishes the two, because *how* it was chosen matters:
/// under `Auto` the name is a live verdict that can change mid-ride, and by
/// hand it is an instruction that will not.
class _AutoProfile extends StatelessWidget {
  const _AutoProfile({
    required this.profile,
    required this.automatic,
    this.snrDb,
    this.pinned = false,
  });

  final NoiseSetting profile;

  /// The onset SNR `Auto` chose this profile from, in dB.
  ///
  /// **The evidence, next to the verdict.** The profile alone says what
  /// happened; a rider whose Auto sits on `Helmet` in a quiet room can see that
  /// it did and nothing about why. With the number, a wrong profile splits into
  /// two different faults that need different fixes — the chain measured the
  /// room wrongly, or it read a correct measurement wrongly.
  ///
  /// Null until the first phrase, and always null when the profile was set by
  /// hand: nothing was chosen from anything, and showing a stale measurement
  /// beside a fixed setting would imply a connection that is not there.
  final double? snrDb;

  /// Whether `Auto` picked this, rather than the rider.
  final bool automatic;

  /// `Auto` is chosen, but the ladder has stopped the classifier — so this
  /// profile can no longer change and is stuck where it stood.
  ///
  /// Worth saying out loud rather than leaving the line looking normal: the
  /// rider asked for a setting that adapts, and it has quietly stopped
  /// adapting. Everything else on the panel reads exactly as it did before.
  final bool pinned;

  @override
  Widget build(BuildContext context) {
    final l = L.of(context);
    final scheme = Theme.of(context).colorScheme;
    return Padding(
      padding: const EdgeInsets.only(bottom: 10),
      child: Row(
        children: [
          Icon(
            automatic ? Icons.auto_mode : Icons.tune,
            size: 14,
            color: scheme.onSurfaceVariant,
          ),
          const SizedBox(width: 6),
          Text(
            automatic ? l.diagAutoProfile : l.diagChosenProfile,
            style: TextStyle(fontSize: 12, color: scheme.onSurfaceVariant),
          ),
          const SizedBox(width: 6),
          Text(
            noiseProfileTitle(l, profile),
            style: TextStyle(
              fontSize: 12,
              fontWeight: FontWeight.w700,
              // Amber, in the same vocabulary the rest of the panel uses for
              // "this device gave something up".
              color: pinned ? StatusColors.connecting : null,
            ),
          ),
          // Grey and in brackets, like the pinned note below: it qualifies
          // the profile rather than competing with it. Whole decibels — the
          // thresholds are 20 dB apart and a decimal would imply a precision
          // the measurement does not have.
          if (snrDb != null) ...[
            const SizedBox(width: 5),
            Text(
              l.diagAutoSnr(snrDb!.round()),
              style: TextStyle(
                fontSize: 11,
                color: scheme.onSurfaceVariant,
                fontFeatures: const [FontFeature.tabularFigures()],
              ),
            ),
          ],
          if (pinned) ...[
            const SizedBox(width: 5),
            // Grey and in brackets: it qualifies the name rather than
            // competing with it, and the name is what is being read.
            Text(
              l.diagProfilePinned,
              style: TextStyle(fontSize: 11, color: scheme.onSurfaceVariant),
            ),
          ],
        ],
      ),
    );
  }
}

