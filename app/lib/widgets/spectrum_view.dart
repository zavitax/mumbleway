class _SpectrumPainter extends CustomPainter {
  const _SpectrumPainter({
    required this.spectrum,
    required this.sending,
    required this.grid,
    required this.raw,
    required this.preGate,
    this.noiseFloorDb,
    this.opensAtDb,
    required this.floorLabel,
    required this.opensAtLabel,
  });

  /// The two dashed marks' labels.
  ///
  /// Passed in rather than looked up, because a painter has no
  /// `BuildContext`. They were literals — "floor" and "opens at" — so the
  /// only English left on a Russian analyser was drawn, not laid out, which
  /// is why no test and no reading of the widget tree would have found it.
  final String floorLabel;
  final String opensAtLabel;

  /// The tracked noise floor and the level a block must beat to be sent, in
  /// dBFS, or null while there is no trustworthy answer.
  ///
  /// **Both are measured after suppression**, which is the same signal the
  /// pre-gate trace is drawn from — so the marks and that trace can honestly be
  /// read against each other. The raw microphone trace is a different signal
  /// and the marks say nothing about it.
  final double? noiseFloorDb;
  final double? opensAtDb;

  final UiSpectrum spectrum;

  /// Whether that block actually left for somebody.
  ///
  /// Not `spectrum.transmitting` on its own. That is the chain's decision —
  /// "this would go out" — and it is deliberately independent of whether there
  /// is a server, because a diagnostic recording made alone still needs it. On
  /// this display, though, green claims the audio *went*, and with nothing
  /// connected it went nowhere. An iPhone in a room with people in it showed
  /// green bars while connected to no server at all; the Android emulator only
  /// looked right because its microphone hears silence.
  final bool sending;
  final Color grid;
  final Color raw;
  final Color preGate;

  /// The sent trace's colour, which is the one piece of state this display
  /// carries that the shapes cannot.
  ///
  /// A flat sent trace means the same shape whether the gate shut or nobody
  /// spoke, and those are opposite diagnoses — so live is a pale green and idle
  /// is grey, and the difference is visible at a glance without reading a
  /// label.
  /// Half transparent so the two thin traces stay readable *through* the bars
  /// rather than being buried by them. The bars are the body of the display and
  /// the lines are what it was made from; at full opacity the body wins and the
  /// comparison — which is the entire point — is lost.
  static Color sentColour(bool transmitting) => transmitting
      ? StatusColors.connected.withValues(alpha: 0.5)
      : const Color(0xFF8A93A0).withValues(alpha: 0.5);

  @override
  void paint(Canvas canvas, Size size) {
    if (spectrum.centresHz.isEmpty) return;
    final floor = spectrum.floorDb;

    double y(double db) {
      final t = ((db - floor) / (0 - floor)).clamp(0.0, 1.0);
      return size.height - t * size.height;
    }

    final lines = Paint()
      ..color = grid
      ..strokeWidth = 1;
    // Every 20 dB, so the eye has a scale without the grid competing with data.
    for (var db = floor; db <= 0; db += 20) {
      final yy = y(db);
      canvas.drawLine(Offset(0, yy), Offset(size.width, yy), lines);
    }

    // The two gate levels, under the traces so they read as a scale rather
    // than as data. Dashed, because a solid line at this weight is
    // indistinguishable from the 20 dB grid and would be read as one.
    void mark(double? db, Color colour, String label) {
      if (db == null || !db.isFinite || db < floor || db > 0) return;
      final yy = y(db);
      final dash = Paint()
        ..color = colour
        ..strokeWidth = 1;
      for (var x = 0.0; x < size.width; x += 7) {
        canvas.drawLine(Offset(x, yy), Offset(x + 4, yy), dash);
      }
      final text = TextPainter(
        text: TextSpan(
          text: label,
          style: TextStyle(fontSize: 9, color: colour),
        ),
        textDirection: TextDirection.ltr,
      )..layout();
      // Above its line where there is room, below it at the very top, so the
      // label never leaves the plot.
      final ty = yy - text.height - 1 < 0 ? yy + 1 : yy - text.height - 1;
      text.paint(canvas, Offset(2, ty));
    }

    // Drawn floor first: where the two coincide — a quiet room, where the
    // threshold sits just over the floor — the one that decides is the one
    // that should be legible.
    mark(noiseFloorDb, grid.withValues(alpha: 0.9), floorLabel);
    mark(opensAtDb, StatusColors.connecting.withValues(alpha: 0.7), opensAtLabel);

    final bands = spectrum.centresHz.length;
    final slot = size.width / bands;

    // Sent first as filled bars, so it reads as the body of the display and the
    // two thin lines read as what it was made from.
    final bars = Paint()..color = sentColour(sending);
    for (var i = 0; i < bands; i++) {
      final top = y(spectrum.sentDb[i]);
      if (top >= size.height) continue;
      canvas.drawRect(
        Rect.fromLTRB(i * slot + 0.5, top, (i + 1) * slot - 0.5, size.height),
        bars,
      );
    }

    void trace(List<double> db, Color colour) {
      final path = Path();
      for (var i = 0; i < bands; i++) {
        final x = i * slot + slot / 2;
        final yy = y(db[i]);
        if (i == 0) {
          path.moveTo(x, yy);
        } else {
          path.lineTo(x, yy);
        }
      }
      canvas.drawPath(
        path,
        Paint()
          ..color = colour
          ..style = PaintingStyle.stroke
          ..strokeWidth = 1.4
          ..strokeJoin = StrokeJoin.round,
      );
    }

    trace(spectrum.rawDb, raw);
    trace(spectrum.preGateDb, preGate);
  }

  @override
  bool shouldRepaint(_SpectrumPainter old) =>
      old.spectrum.seq != spectrum.seq ||
      old.sending != sending ||
      // The gate marks move on their own clock: the floor tracker settles
      // while the spectrum is unchanged, and a mark that only redrew when a
      // new frame arrived would sit at a stale level through exactly the
      // moments worth watching.
      old.noiseFloorDb != noiseFloorDb ||
      old.opensAtDb != opensAtDb ||
      // Switching language changes nothing else here — same frame, same
      // levels — so without this the plot keeps its old labels until the next
      // block arrives, which on a settled analyser can be a visible while.
      old.floorLabel != floorLabel ||
      old.opensAtLabel != opensAtLabel;
}

/// The processing chain as a row of dots, in the order audio passes through it.
class _ChainDots extends StatelessWidget {
  const _ChainDots({required this.status});

  final UiChainStatus status;

  @override
  Widget build(BuildContext context) {
    final l = L.of(context);
    return Wrap(
      spacing: 12,
      runSpacing: 8,
      children: [
        for (final stage in status.stages)
          _Dot(
            label: _label(l, stage),
            state: stage.state,
            value: stage.value,
            disabled: status.disabledStages.contains(stage.id),
            // Amber name, not just an amber dot.
            //
            // **Most amber on this row is transient and one kind is not.** The
            // echo canceller goes amber while it converges, the AGC while it
            // is at its ceiling, the gate while it is closed — all of them
            // describe this instant and will be green again shortly. The
            // enhancer's amber says it has *permanently given something up on
            // this device*, which is the same fact the strike-through carries
            // one step further on. Colouring the name is what separates the
            // two: a state you are watching, against a state you are stuck
            // with.
            degraded: stage.id == 'enhancer' && status.enhancerEffort > 0,
          ),
      ],
    );
  }

  /// Composed here rather than sent from Rust: everything else on this panel is
  /// translated, and a message built in the engine would be the one string a
  /// translator could not reach.
  String _label(L l, UiStage stage) => switch (stage.id) {
    // Listed in the order the chain runs them, matching the order the bridge
    // sends. A lookup does not care, but the next person reading it does.
    // The canceller is ahead of the enhancer — `engine.rs` says why.
    'aec' => l.diagStageEcho,
    'enhancer' => l.diagStageEnhancer,
    'rnnoise' => l.diagStageSuppressor,
    'vad' => l.diagStageVoice,
    'gate' => l.diagStageGate,
    'agc' => l.diagStageLevel,
    'feedback' => l.diagStageFeedback,
    'dehiss' => l.diagStageHiss,
    'background' => l.diagStageBackground,
    'transmit' => l.diagStageTransmit,
    _ => stage.id,
  };
}

class _Dot extends StatelessWidget {
  const _Dot({
    required this.label,
    required this.state,
    required this.value,
    this.disabled = false,
    this.degraded = false,
  });

  final String label;
  final StageState state;
  final double value;

  /// Still running, but the performance ladder has taken something off it.
  ///
  /// One step short of [disabled], and shown the same way for the same reason
  /// — an amber name means "this device gave this up", where an amber dot on
  /// its own only means "this stage is busy right now".
  final bool degraded;

  /// Switched off by the performance ladder, rather than idle.
  ///
  /// **The distinction the strike-through exists for.** A stage that is not
  /// running publishes the same greys and zeroes as one that is running with
  /// nothing to do, so without this a crippled chain and a quiet one look
  /// identical — which is precisely the class of blind spot that cost this
  /// project an evening over the input meter.
  final bool disabled;

  @override
  Widget build(BuildContext context) {
    final scheme = Theme.of(context).colorScheme;
    // The app's own status vocabulary, so a dot here means what a dot means
    // everywhere else in the interface.
    final colour = disabled
        ? StatusColors.connecting
        : switch (state) {
            StageState.good => StatusColors.connected,
            StageState.warn => StatusColors.connecting,
            StageState.bad => StatusColors.failed,
            StageState.off => scheme.onSurfaceVariant.withValues(alpha: 0.35),
          };

    return Row(
      mainAxisSize: MainAxisSize.min,
      children: [
        Container(
          width: 8,
          height: 8,
          decoration: BoxDecoration(
            // Hollow when it is not running: a filled dot says "this stage has
            // an opinion", and a stage that has been switched off does not.
            color: disabled ? null : colour,
            border: disabled ? Border.all(color: colour, width: 1.5) : null,
            shape: BoxShape.circle,
          ),
        ),
        const SizedBox(width: 5),
        Text(
          label,
          style: TextStyle(
            fontSize: 11,
            // **Dimmed when switched off, amber only when degraded.**
            //
            // Both used to be amber, and the strike-through was amber on top
            // of amber: at 11 px a same-coloured line through same-coloured
            // glyphs is not a strike-through, it is slightly bolder text.
            // Magnifying a screenshot five times showed the line was there and
            // being drawn correctly the whole time — it simply could not be
            // seen at the size it ships at, which is the only size that counts.
            //
            // So the two states are now told apart by more than a line nobody
            // can see: a stage still doing most of its job keeps the amber
            // name, and one that is not running at all goes quiet and gets a
            // line across it that contrasts with the letters it crosses.
            color: degraded
                ? StatusColors.connecting
                : scheme.onSurfaceVariant.withValues(alpha: disabled ? 0.6 : 1),
            // Struck through only when it is genuinely not running. A degraded
            // stage is still doing most of its job, and striking it out would
            // say otherwise.
            decoration: disabled ? TextDecoration.lineThrough : null,
            decorationColor: disabled ? StatusColors.connecting : null,
            decorationThickness: disabled ? 2 : null,
          ),
        ),
      ],
    );
  }
}
